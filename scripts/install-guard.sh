#!/bin/sh
# Installs the push and post guard outside the checkout (CLAUDE.md → Commands). The owner runs it from
# the repository root, once per clone and after every change to scripts/guard/:
#   scripts/install-guard.sh
# It copies scripts/guard/ to ~/.config/moonshine/guard/, writes the git hook and the gh-post command
# that run that copy, records this project's scratchpad root for gh-post, and points core.hooksPath
# (this repository only) at the absolute hook folder, so a checkout without the guard, or with an
# edited one, cannot change what runs. MOONSHINE_GUARD_DIR and MOONSHINE_SCRATCH_ROOT override the
# two locations (tests use them).
set -eu

source_dir=$(cd "$(dirname "$0")/guard" && pwd)
top=$(git rev-parse --show-toplevel)
dir=${MOONSHINE_GUARD_DIR:-$HOME/.config/moonshine}
slug=$(printf '%s' "$top" | sed 's/[^A-Za-z0-9]/-/g')
scratch=${MOONSHINE_SCRATCH_ROOT:-/private/tmp/claude-$(id -u)/$slug}

# Both paths are written into generated files: refuse characters that would need quoting there.
for path in "$dir" "$scratch"; do
  case $path in
    /*) ;;
    *) echo "install-guard: $path is not absolute." >&2; exit 1 ;;
  esac
  case $path in
    *\'* | *\"* | *\\* | *"
"*) echo "install-guard: a path contains a quote, a backslash or a newline." >&2; exit 1 ;;
  esac
done

mkdir -p "$dir/guard" "$dir/hooks" "$dir/bin"
for file in matcher.mjs pre-push.mjs gh-post.mjs; do
  cp "$source_dir/$file" "$dir/guard/$file"
done
printf '{ "scratchRoot": "%s" }\n' "$scratch" > "$dir/guard/config.json"

printf '#!/bin/sh\n# Generated by scripts/install-guard.sh. Without node, the push is blocked.\nexec node '\''%s/guard/pre-push.mjs'\'' "$@"\n' "$dir" > "$dir/hooks/pre-push"
printf '#!/bin/sh\n# Generated by scripts/install-guard.sh.\nexec node '\''%s/guard/gh-post.mjs'\'' "$@"\n' "$dir" > "$dir/bin/gh-post"
chmod 755 "$dir/hooks/pre-push" "$dir/bin/gh-post"

git config core.hooksPath "$dir/hooks"

echo "install-guard: guard installed in $dir; core.hooksPath set for $top."
echo "install-guard: gh-post is $dir/bin/gh-post; scratchpad root $scratch."
if ! git config --get moonshine.denyList > /dev/null; then
  echo "install-guard: moonshine.denyList is not set; every push and post is blocked until it is." >&2
fi
